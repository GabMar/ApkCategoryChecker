/**
 * Regenerates `sdks/libchecker-rules.json` from LibChecker-Rules (Apache-2.0,
 * https://github.com/LibChecker/LibChecker-Rules): its canonical `libraries/<uuid>.json` files are
 * reduced to the matchers this tool can evaluate and an English label per library.
 *
 * Run with `./gradlew updateSdkRules [-Pref=<branch, tag or commit>]` (or `just update-sdk-rules`).
 */
fun main(args: Array<String>) {
    val ref = args.getOrElse(0) { "v4" }
    val output = Path.of(args.getOrElse(1) { "src/main/resources/sdks" }).createDirectories()
    val http = HttpClient.newBuilder().followRedirects(HttpClient.Redirect.NORMAL).build()

    fun get(url: String): ByteArray {
        val request = HttpRequest.newBuilder(URI(url)).header("User-Agent", "apk-category-checker")
        System
            .getenv(
                "GITHUB_TOKEN",
            )?.takeIf { url.startsWith("https://api.github.com/") }
            ?.let { request.header("Authorization", "Bearer $it") }
        val response = http.send(request.build(), HttpResponse.BodyHandlers.ofByteArray())
        check(response.statusCode() == 200) { "HTTP ${response.statusCode()} for $url" }
        return response.body()
    }

    val commit =
        Json
            .parseToJsonElement(String(get("https://api.github.com/repos/$REPOSITORY/commits/$ref")))
            .jsonObject["sha"]!!
            .jsonPrimitive.content
    val files = mutableMapOf<String, ByteArray>()
    ZipInputStream(ByteArrayInputStream(get("https://codeload.github.com/$REPOSITORY/zip/$commit"))).use { zip ->
        generateSequence { zip.nextEntry }.forEach { entry ->
            val path = entry.name.substringAfter('/') // drop the enclosing directory
            if (path == "LICENSE" || (path.startsWith("libraries/") && path.endsWith(".json"))) files[path] = zip.readAllBytes()
        }
    }

    val libraries = files.filterKeys { it.startsWith("libraries/") }.values.map { Json.parseToJsonElement(String(it)).jsonObject }
    check(libraries.isNotEmpty()) { "no libraries in $REPOSITORY@$commit" }
    val rules = mutableListOf<JsonObject>()
    val labels = sortedMapOf<String, JsonObject>()
    for (entry in libraries) {
        val uuid = entry.string("uuid")!!
        for (matcher in entry["matchers"]!!.jsonArray.map { it.jsonObject }) {
            val type = matcher["type"]!!.jsonPrimitive.int
            if (type !in SUPPORTED_TYPES) continue
            val name = matcher.string("name")!!
            val correction = CORRECTIONS.firstOrNull { it.type == TYPE_NAMES[type] && it.matches(name) }
            if (correction is Correction.Exclude) continue
            val library =
                (correction as? Correction.Relabel)?.let { relabeled ->
                    "override:${relabeled.label}".also { labels[it] = relabeled.info() }
                } ?: uuid
            rules +=
                buildJsonObject {
                    put("type", TYPE_NAMES.getValue(type))
                    put("name", name)
                    put("regex", matcher.string("mode") == "regex")
                    put("priority", matcher["priority"]!!.jsonPrimitive.int)
                    put("id", matcher["id"]!!.jsonPrimitive.int)
                    put("library", library)
                }
            if (library !in labels) labels[library] = libraryInfo(entry, matcher)
        }
    }
    rules.sortWith(compareBy({ it.string("type") }, { it["priority"]!!.jsonPrimitive.int }, { it["id"]!!.jsonPrimitive.int }))

    val json =
        buildJsonObject {
            put(
                "source",
                buildJsonObject {
                    put("repository", "https://github.com/$REPOSITORY")
                    put("commit", commit)
                    put("license", "Apache-2.0, see LICENSE-LibChecker-Rules")
                    put("note", "Generated by ./gradlew updateSdkRules: do not edit by hand.")
                },
            )
            put("corrections", JsonArray(CORRECTIONS.map { it.describe() }))
            put("libraries", JsonObject(labels))
            put("rules", JsonArray(rules))
        }
    output.resolve("libchecker-rules.json").writeText(PRETTY.encodeToString(JsonElement.serializer(), json) + "\n")
    output.resolve("LICENSE-LibChecker-Rules").writeBytes(files.getValue("LICENSE"))
    println("Wrote ${rules.size} rules for ${labels.size} libraries from $REPOSITORY@$commit to $output")
}

/** The English label, team and link of a library, as LibChecker shows them (the matcher's label as a fallback). */
private fun libraryInfo(
    library: JsonObject,
    matcher: JsonObject,
): JsonObject {
    // A matcher's detailData overrides the library's data; it may be absent or explicitly null.
    val locales = ((matcher["detailData"] as? JsonArray) ?: (library["data"] as? JsonArray)).orEmpty().map { it.jsonObject }
    val english = locales.firstOrNull { it.string("locale") == "en" }?.get("data")?.jsonObject
    return buildJsonObject {
        put("label", english?.string("label")?.takeIf { it.isNotBlank() } ?: matcher.string("label"))
        english?.string("dev_team")?.takeIf { it.isNotBlank() }?.let { put("team", it) }
        english?.string("source_link")?.takeIf { it.isNotBlank() }?.let { put("link", it) }
    }
}

private fun JsonObject.string(key: String): String? = (this[key] as? JsonPrimitive)?.takeIf { it != JsonNull }?.contentOrNull

private const val REPOSITORY = "LibChecker/LibChecker-Rules"

/** Upstream rules that attribute files to the wrong SDK, found checking the corpus apps. */
private sealed class Correction(
    val type: String,
    private val name: Regex,
    val reason: String,
) {
    fun matches(ruleName: String) = name.matches(ruleName)

    class Exclude(
        type: String,
        name: Regex,
        reason: String,
    ) : Correction(type, name, reason)

    class Relabel(
        type: String,
        name: Regex,
        val label: String,
        private val team: String,
        reason: String,
    ) : Correction(type, name, reason) {
        fun info() =
            buildJsonObject {
                put("label", label)
                put("team", team)
            }
    }

    fun describe() =
        buildJsonObject {
            put("type", type)
            put("rule", name.pattern)
            put("action", if (this@Correction is Relabel) "relabel as $label" else "exclude")
            put("reason", reason)
        }
}

private val CORRECTIONS =
    listOf(
        Correction.Exclude(
            "nativeLib",
            Regex("libmain\\.so"),
            "a generic name: SDL and python-for-android apps ship it too, not only Unity",
        ),
        Correction.Exclude(
            "nativeLib",
            Regex("libstlport_shared\\.so"),
            "the STLport C++ runtime, shipped by many apps, not only SQLCipher",
        ),
        Correction.Exclude(
            "nativeLib",
            Regex("libfb(jni)?\\.so"),
            "Meta's JNI helpers, used by React Native and Fresco: not the Facebook SDK for Facebook login and sharing",
        ),
        Correction.Relabel(
            "nativeLib",
            Regex("libreact_nativemodule_core\\.so"),
            "React Native",
            "Meta",
            "part of React Native itself, not of Reanimated",
        ),
        Correction.Relabel(
            "nativeLib",
            Regex("libplugins_.*"),
            "Qt",
            "The Qt Company",
            "Qt plugins keep this naming in Qt 6, so they are not specific to Qt5",
        ),
    )

/** LibChecker matcher types this tool evaluates (static libraries, permissions and meta-data rules are not). */
private val TYPE_NAMES =
    mapOf(
        0 to "nativeLib",
        1 to "service",
        2 to "activity",
        3 to "receiver",
        4 to "provider",
        5 to "dex",
        9 to "action",
    )
private val SUPPORTED_TYPES = TYPE_NAMES.keys

private val PRETTY = Json { prettyPrint = true }
